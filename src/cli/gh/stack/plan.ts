import { Array as EffectArray, Option, String as EffectString } from "effect";

import type { PullRequestNumber, RemoteStack, StackNumber } from "../../../clients/github/types";

export const basesFor = (branches: readonly string[], trunk: string): readonly string[] => [
  trunk,
  ...branches.slice(0, -1),
];

export type Registration =
  | {
      readonly _tag: "Append";
      readonly pullRequests: readonly PullRequestNumber[];
      readonly stack: StackNumber;
    }
  | { readonly _tag: "Create"; readonly pullRequests: readonly PullRequestNumber[] }
  | { readonly _tag: "Unchanged" };

/**
 * `wanted` runs bottom to top, with `none` for a pull request not opened yet. GitHub rejects base
 * changes in a stack and only adds to its top. So the stack stays only where no base moves, and one
 * of the two lists, its unmerged pull requests and the wanted ones, is the other's bottom part.
 */
export const mustDissolve = (
  existing: Option.Option<RemoteStack>,
  wanted: readonly Option.Option<PullRequestNumber>[],
  basesMove: boolean,
): boolean => {
  if (Option.isNone(existing)) {
    return false;
  }
  const { unmerged } = existing.value;
  const matches = (index: number): boolean => {
    const pullRequest = wanted[index];
    return (
      pullRequest !== undefined &&
      Option.isSome(pullRequest) &&
      pullRequest.value === unmerged[index]
    );
  };
  const shorter = Math.min(unmerged.length, wanted.length);
  const agree =
    shorter > 0 &&
    EffectArray.every(
      Array.from({ length: shorter }, (_, index) => index),
      (index) => matches(index),
    );
  return basesMove || !agree;
};

// A single pull request can't be a stack.
export const registrationFor = (
  remaining: Option.Option<RemoteStack>,
  wanted: readonly PullRequestNumber[],
): Registration => {
  if (Option.isNone(remaining)) {
    return wanted.length > 1 ? { _tag: "Create", pullRequests: wanted } : { _tag: "Unchanged" };
  }
  const { number, unmerged } = remaining.value;
  return wanted.length > unmerged.length
    ? { _tag: "Append", pullRequests: wanted.slice(unmerged.length), stack: number }
    : { _tag: "Unchanged" };
};

// The body keeps its first line's indent, which Markdown reads as a code block or nested list item.
export const titleAndBody = (
  description: string,
): { readonly body: string; readonly title: string } => {
  const [title, ...rest] = EffectString.split(EffectString.trimEnd(description), "\n");
  return { body: EffectString.replace(/^\s*\n/u, "")(EffectArray.join(rest, "\n")), title };
};

export const descriptionFrom = ({
  body,
  title,
}: {
  readonly body: string;
  readonly title: string;
}): string => (body === "" ? title : `${title}\n\n${body}`);

// A Claude Code cloud session's GitHub proxy appends it to each pull request body it creates or
// edits, with or without the session's path in the link.
const claudeCodeFooter =
  /\n*---\n_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code[^\s)]*\)_\s*$/u;

/**
 * GitHub stores browser-edited bodies with Windows line endings, and jj ends descriptions with a
 * newline. With `ignoreClaudeCodeFooter`, drops the proxy's footer, which returns on each edit
 * through the proxy.
 */
export const normalizedDescription = (
  description: string,
  { ignoreClaudeCodeFooter }: { readonly ignoreClaudeCodeFooter: boolean },
): string => {
  const text = EffectString.replaceAll("\r\n", "\n")(description);
  return descriptionFrom(
    titleAndBody(ignoreClaudeCodeFooter ? EffectString.replace(claudeCodeFooter, "")(text) : text),
  );
};

export type DescriptionSync =
  | { readonly _tag: "InSync" }
  | { readonly _tag: "Merge" }
  | { readonly _tag: "SendLocal" }
  | { readonly _tag: "TakeGitHub" };

export const agreedDescription = ({
  isOwnEarlier,
  onGitHub,
  pushed,
  recorded,
}: {
  readonly isOwnEarlier: boolean;
  readonly onGitHub: string;
  readonly pushed: string;
  readonly recorded: Option.Option<string>;
}): string => Option.getOrElse(recorded, () => (isOwnEarlier ? onGitHub : pushed));

export const descriptionSyncFor = ({
  agreed,
  local,
  onGitHub,
}: {
  readonly agreed: string;
  readonly local: string;
  readonly onGitHub: string;
}): DescriptionSync => {
  if (local === onGitHub) {
    return { _tag: "InSync" };
  }
  if (local === agreed) {
    return { _tag: "TakeGitHub" };
  }
  return onGitHub === agreed ? { _tag: "SendLocal" } : { _tag: "Merge" };
};
