/** The setting's value, or its default if the key is unset. Fails on any other value. */
export const readSetting = <A extends boolean | string>(
  setting: Setting<A>,
): Effect.Effect<A, JjFailed, Jj> =>
  Effect.gen(function* () {
    const value = yield* readJjConfig(setting.key);
    if (value === undefined) {
      return yield* setting.default.value;
    }
    const choice = EffectArray.findFirst(setting.choices, (candidate) => candidate.value === value);
    if (Option.isNone(choice)) {
      const values = EffectArray.join(
        EffectArray.map(setting.choices, (candidate) => String(candidate.value)),
        " or ",
      );
      return yield* JjFailed.make({
        message: `${setting.key} is ${formatJson(value)}; set it to ${values}`,
      });
    }
    return choice.value.value;
  });
